# 字符串操作常用方法：

# find()
# 作用：在字符串中查找子串，返回第一次出现的索引位置，找不到返回 -1
# 示例：
s = "Hello-Python-Hello-World"
s.find('Python')


# count()
# 作用：统计子串在字符串中出现的次数
# 示例：
s.count('H')


# upper()
# 作用：将字符串中的所有字母转换为大写
# 示例：
su = s.upper()
print("slist")


# lower()
# 作用：将字符串中的所有字母转换为小写
# 示例：
s.lower()


# split()   切割
# 作用：将字符串按照指定分隔符分割成列表
# 示例：
s.split('- ')


# strip()
# 作用：去除字符串两端的空白字符或指定字符
# 示例：
s.strip()
s.strip('*')


# replace()
# 作用：将字符串中的指定子串替换为新的子串
# 示例：
s.replace('H', 'C')

# startswith()
# 作用：检查字符串是否以指定子串开头，返回布尔值
# 示例：
s.startswith('P')


# 每次通过函数就会得到一个新的字符串,但是假如我们将所有的函数过了一遍之后,原来的字符串就不会改变